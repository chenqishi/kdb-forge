def convert_label_to_language(label):
    """将 fastText 的标签（如 __label__ja）转换为语言名称"""
    # 移除 __label__ 前缀
    code = label.replace('__label__', '')
    # 从映射表中获取语言名称，如果没有则返回代码本身
    return LANGUAGE_MAP.get(code, code)
