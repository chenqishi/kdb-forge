#!/usr/bin/env python3
"""Compare the undeployed count API with native ES8 counts on two existing indices.

Default: print a local execution plan without imports, network or output files.
--execute: in-process TestClient, real service/engine/official ES client, count only.
No listener, deployment, source ES, document reads, embedding, index creation or writes.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import secrets
import sys
from datetime import datetime, timezone
from unittest.mock import patch


ROOT = Path(__file__).resolve().parents[1]
INDEX_PROVIDERS = {"mercado_local": "serverless", "payoneer_olive": "paas"}
MAX_COUNT_REQUESTS = 24


class AuditFailure(RuntimeError):
    """Sanitized failure codes generated by this audit, never ES response text."""


def utc_now():
    return datetime.now(timezone.utc).isoformat()


def read_json(path):
    return json.loads(Path(path).read_text())


def digest(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def cases(start, end):
    return [
        ("default_chat_auto", {}, "chat_auto", None),
        ("closed_window_camel_alias", {"from_type": "chat_auto", "start": start, "end": end}, "chat_auto", (start, end)),
        ("explicit_document", {"from_type": "document"}, "document", None),
        ("explicit_unmatched", {"from_type": "learning-count-no-match-20261008"}, "learning-count-no-match-20261008", None),
        ("valid_single_bound", {"start": start}, "chat_auto", None),
        ("reversed_window", {"start": end, "end": start}, "chat_auto", (end, start)),
    ]


def native_query(from_type, window):
    filters = [{"term": {"quality_level": "high"}}, {"term": {"from_type": from_type}}]
    if window:
        filters.append({"range": {"insert_time": {"gte": window[0], "lte": window[1]}}})
    return {"bool": {"filter": filters}}


def require(value, message):
    if not value:
        raise AuditFailure(message)


def execute(args, report):
    # Bind the selected config to the already-established new runtime endpoints;
    # never emit hosts, credentials, request bodies or raw ES exceptions.
    runtime = read_json(args.config)
    engine_path = Path(runtime["engine_config_path"])
    if not engine_path.is_absolute():
        engine_path = Path.cwd() / engine_path
    engine_config = read_json(engine_path)
    known_targets = read_json(args.target_config)
    require(str(engine_config.get("es_version")) == "8.17", "runtime_not_es817")
    require(str(known_targets.get("es_version")) == "8.17", "target_reference_not_es817")
    endpoint_hashes = {}
    for provider in INDEX_PROVIDERS.values():
        actual = engine_config["providers"][provider]
        known = known_targets["providers"][provider]
        hosts = actual.get("hosts") or actual.get("host")
        require(hosts and hosts == (known.get("hosts") or known.get("host")), "runtime_target_endpoint_mismatch")
        endpoint_hashes[provider] = digest(hosts)
    report["target_endpoint_sha256"] = endpoint_hashes
    report["runtime_config_sha256"] = hashlib.sha256(Path(args.config).read_bytes()).hexdigest()

    sys.path.insert(0, str(ROOT / "src"))
    from elasticsearch import Elasticsearch
    from fastapi.testclient import TestClient
    from kdb.api import search_routes
    from kdb.api.retrieval_app import app
    from kdb.crud import service as service_module
    from kdb.es import engine as engine_module

    require(ROOT / "src" in Path(engine_module.__file__).resolve().parents, "wrong_checkout_imported")
    require(hasattr(service_module.KnowledgeService, "from_count_config"), "count_factory_not_implemented")
    require(hasattr(search_routes, "_count_service"), "count_api_not_implemented")
    original_request = Elasticsearch.perform_request
    calls = []
    allowed_paths = {f"/{name}/_count" for name in INDEX_PROVIDERS}

    def count_only(self, method, path, *positional, **kwargs):
        require(method in {"GET", "POST"} and path in allowed_paths, "non_count_es_request_blocked")
        calls.append({"method": method, "path": path})
        require(len(calls) <= MAX_COUNT_REQUESTS, "count_request_budget_exceeded")
        return original_request(self, method, path, *positional, **kwargs)

    def forbidden(*_args, **_kwargs):
        raise AuditFailure("embedding_or_ensure_forbidden")

    direct_service = None
    api_service = None
    user, password = "count-audit", secrets.token_urlsafe(24)
    try:
        with patch.dict(os.environ, {"KDB_FORGE_CONFIG": str(Path(args.config).resolve()),
                                     "KDB_SEARCH_BASIC_USER": user,
                                     "KDB_SEARCH_BASIC_PASSWORD": password,
                                     "KDB_SEARCH_ALLOW_LOOPBACK": "0"}), \
             patch.object(Elasticsearch, "perform_request", count_only), \
             patch.object(engine_module.RoutedLegacyEngine, "_ensure_index", forbidden), \
             patch.object(service_module, "build_embedding_client", forbidden), \
             patch.object(search_routes, "_count_service", None):
            with TestClient(app) as http:
                denied = http.post("/get_from_type_count", json={"index_name": "mercado_local"})
                require(denied.status_code == 401 and not calls, "count_api_auth_gate_failed")
                report["in_process_auth_pass"] = True
                for label, request in [("empty_index", {"index_name": ""}),
                                       ("null_index", {"index_name": None}), ("omitted_index", {})]:
                    result = http.post("/get_from_type_count", auth=(user, password), json=request)
                    body = result.json()
                    passed = (result.status_code == 200 and body.get("success") is True
                              and type(body.get("count")) is int and body["count"] == 0
                              and not calls and search_routes._count_service is None)
                    report["cases"].append({"index": None, "case": label, "http_status": result.status_code,
                                            "api_count": body.get("count"), "es_requests": 0, "passed": passed})
                    require(passed, "empty_index_triggered_io_or_failed")
                direct_service = service_module.KnowledgeService.from_count_config(args.config)
                require(direct_service._embedding is None and not calls, "count_factory_performed_io")
                engine = direct_service._repo._engine
                for index, provider in INDEX_PROVIDERS.items():
                    require(engine.router.resolve_provider(index) == provider, "provider_binding_mismatch")
                    client = engine.get_client_by_index(index)
                    for name, parameters, from_type, window in cases(args.start, args.end):
                        query = native_query(from_type, window)
                        response = client.count(index=index, query=query)
                        body = response.body if hasattr(response, "body") else response
                        shards = body.get("_shards") or {}
                        count = body.get("count")
                        total, successful, failed = (shards.get(field) for field in ("total", "successful", "failed"))
                        require(type(count) is int and count >= 0
                                and all(type(value) is int for value in (total, successful, failed))
                                and total > 0 and successful == total and failed == 0
                                and not shards.get("failures") and not body.get("failures")
                                and not body.get("error")
                                and all(field not in body or body[field] is False
                                        for field in ("timed_out", "terminated_early")),
                                "native_count_incomplete")
                        if name in {"explicit_unmatched", "reversed_window"}:
                            require(count == 0, "expected_zero_count_was_nonzero")
                        index_key = "indexName" if name.endswith("camel_alias") else "index_name"
                        result = http.post("/get_from_type_count", auth=(user, password),
                                           json={index_key: index, **parameters})
                        api_service = search_routes._count_service
                        payload = result.json()
                        passed = (result.status_code == 200 and payload.get("success") is True
                                  and type(payload.get("count")) is int and payload["count"] == count
                                  and isinstance(payload.get("message"), str))
                        report["cases"].append({"index": index, "provider": provider, "case": name,
                                                "native_count": count, "api_count": payload.get("count"),
                                                "http_status": result.status_code, "passed": passed})
                        require(passed, "native_api_count_mismatch")
                api_service = search_routes._count_service
                require(api_service is not None and api_service._embedding is None, "api_count_factory_not_used")
                require(len(calls) == MAX_COUNT_REQUESTS, "count_request_budget_not_fully_observed")
    finally:
        # Close only clients instantiated by this in-process audit.
        for service in (direct_service, api_service):
            if service is not None:
                service._repo._engine.close()
        report["es_count_requests"] = len(calls)
        report["es_request_paths"] = sorted({call["path"] for call in calls})


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--execute", action="store_true")
    parser.add_argument("--config", default="/root/kdb-forge/config/config_search_runtime.local.json")
    parser.add_argument("--target-config", default="/root/kdb-forge/config/config_es_runtime.local.json")
    parser.add_argument("--start", default="2026-09-01 00:00:00")
    parser.add_argument("--end", default="2026-10-08 23:59:59")
    parser.add_argument("--report", default="artifacts/from_type_count_readonly_20261008.json")
    args = parser.parse_args()
    report = {"task": "LEARNING-COUNT-API-20261008", "started_at_utc": utc_now(),
              "mode": "execute" if args.execute else "plan", "read_only": True,
              "old_es_requests": 0, "service_deployed_or_restarted": False,
              "http_listener_started": False, "live_8012_endpoint_tested": False,
              "freshness_proven": False, "indices": INDEX_PROVIDERS, "cases": [],
              "max_count_requests": MAX_COUNT_REQUESTS, "all_pass": False}
    if not args.execute:
        report.update(status="prepared", network_requests=0, output_files_written=0,
                      planned_cases=[row[0] for row in cases(args.start, args.end)])
        print(json.dumps(report, ensure_ascii=False))
        return 0
    try:
        execute(args, report)
        report.update(status="complete", all_pass=True)
    except Exception as exc:
        # ES exception strings may contain hosts or credentials.
        report.update(status="failed", error_type=type(exc).__name__)
        if isinstance(exc, AuditFailure):
            report["failure_reason"] = str(exc)
    report["finished_at_utc"] = utc_now()
    output = Path(args.report)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps({"report": str(output), "status": report["status"], "all_pass": report["all_pass"],
                      "es_count_requests": report.get("es_count_requests", 0)}, ensure_ascii=False))
    return 0 if report["all_pass"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
